// Rack RP2350 — speaker cab impulse response for the Swedish Chainsaw
// (FX TYPE = SWEDE, applied after the FMV tonestack; the Barabas5532 plugin
// this algo is ported from also convolves a speaker IR at the same point).
//
// Regenerate with: uv run --with numpy python tools/ir2array.py "<wav>" 1024 16000
// (the script prints the constants; paste them here). Source file:
// tools/Hesu 2x12 V30 - 440 center edge.wav — 44.1 kHz mono 24-bit, 1.83 s.
// 1024 taps @ 16 kHz = 64 ms — the conv runs at the DECIMATED rate (the IR is
// band-limited to 8 kHz: only 0.42% of its energy sits above; a V30 cab has
// nothing up there). 1024 taps = 99.9% of the compacted body energy (the
// 512-tap window held 98.8% — the extra half-window is the cab's decay tail).
// The float IR table is gone: its only consumer (the bypass-energy sum)
// ships as kSpeakerIrRms, which keeps the tc_elements SRAM slot within its
// 60,416 B A-slot budget (the tables alone would have overrun it by 8 B).
// The FIR runs as a q15 int16 dual-MAC (SMLALD, M33 DSP extension — Yiu
// ch.19.4): kSpeakerIrQ15 packs the IR in chronological int16 pairs scaled
// so the PEAK coefficient hits full 15-bit scale (the 64-bit SMLALD
// accumulator cannot overflow: sum|ir16| x 32767 ~= 1.3e10 << 2^63);
// kSpeakerQ15Norm converts the accumulator back.
